# Generates the demo's pen cursors (demo/cursors/*.cur) and their resource script (demo/cursors/cursors.rc): a filled dot
# in the preset's color, its diameter the stroke's drawn width - pens: Xournal's width at full
# pressure / 1.75 (Windows ink draws that at half pressure), highlighters: their width. One cursor per palette color x
# width step (InkPages' Palette, PenWidths, HighlighterWidths). Each .cur holds 32 and 48 px images (100 / 150 %);
# Windows picks the image for its cursor size and DPI. Resource ids: pens 1000 + color * 10 + step, highlighters
# 2000 + color * 10 + step (demo/main.cpp).
# Run: python demo/tools/make_cursors.py
import struct
from pathlib import Path

PENS = [0x000000, 0x3333CC, 0xFF0000, 0x008000, 0x808080, 0x00C0FF, 0x00FF00, 0xFF00FF, 0xFF8000, 0xFFFF00]
HIGHLIGHTERS = [
    0xFFFF00, 0x00FF00, 0x00C0FF, 0xFF00FF, 0xFF8000, 0xFF5858,
    0xFF9CC8, 0xB791F5, 0x75A7FF, 0x00CCB4, 0xA2EBBC, 0xFFD180,
]
PEN_WIDTHS = [0.42, 0.85, 1.41, 2.26, 5.67]
HIGHLIGHTER_WIDTHS = [1, 2.83, 8.5, 19.84, 30]
SIZES = [32, 48]


def coverage(px, py, c, r):
    near_x = max(px - c, c - px - 1, 0)
    near_y = max(py - c, c - py - 1, 0)
    if near_x ** 2 + near_y ** 2 >= r * r:
        return 0
    if max(abs(px - c), abs(px + 1 - c)) ** 2 + max(abs(py - c), abs(py + 1 - c)) ** 2 <= r * r:
        return 1
    samples = 16
    hits = 0
    for sy in range(samples):
        for sx in range(samples):
            x = px + (sx + 0.5) / samples
            y = py + (sy + 0.5) / samples
            if (x - c) ** 2 + (y - c) ** 2 <= r * r:
                hits += 1
    return hits / (samples * samples)


def image(size, rgb, diameter_dip):
    scale = size / 32
    c = size / 2
    r = diameter_dip * scale / 2
    color = ((rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF)
    rows = []
    for y in range(size - 1, -1, -1):  # bottom-up
        row = bytearray()
        for x in range(size):
            alpha = round(coverage(x, y, c, r) * 255)
            row += bytes((color[2], color[1], color[0], alpha)) if alpha else bytes(4)
        rows.append(bytes(row))
    xor = b"".join(rows)
    and_mask = bytes(((size + 31) // 32) * 4 * size)
    header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, len(xor) + len(and_mask), 0, 0, 0, 0)
    return header + xor + and_mask


def cursor(rgb, diameter):
    images = [image(s, rgb, diameter) for s in SIZES]
    out = struct.pack("<HHH", 0, 2, len(SIZES))
    offset = 6 + 16 * len(SIZES)
    for s, data in zip(SIZES, images):
        out += struct.pack("<BBBBHHII", s, s, 0, 0, s // 2, s // 2, len(data), offset)
        offset += len(data)
    return out + b"".join(images)


root = Path(__file__).resolve().parent.parent / "cursors"
root.mkdir(exist_ok=True)
rc = ["// Generated by demo/tools/make_cursors.py - pen cursors per color x width."]
for ci, rgb in enumerate(PENS):
    for si, w in enumerate(PEN_WIDTHS):
        name = f"pen_{ci}_{si}.cur"
        (root / name).write_bytes(cursor(rgb, w / 1.75))
        rc.append(f'{1000 + ci * 10 + si} CURSOR "cursors/{name}"')
for ci, rgb in enumerate(HIGHLIGHTERS):
    for si, w in enumerate(HIGHLIGHTER_WIDTHS):
        name = f"highlighter_{ci}_{si}.cur"
        (root / name).write_bytes(cursor(rgb, w))
        rc.append(f'{2000 + ci * 10 + si} CURSOR "cursors/{name}"')
(root / "cursors.rc").write_text("\n".join(rc) + "\n", encoding="utf-8")
print(f"{len(rc) - 1} cursors")
